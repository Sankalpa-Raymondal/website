// Turns the Markdown entries of Blogs, Books and Movies into HTML pages.
//
//   npm run build    convert everything once (do this before pushing)
//   npm run watch    keep converting whenever a .md file is saved (handy with Live Server)
//
// For each section, every blogs/blog_entries/<name>.md becomes blogs/<name>.html,
// and blogs/entries.json lists them all for the section's index.html to show.
// Files starting with "_" (like _template.md) are skipped.
//
// Entry format (all optional except the text):
//   # Title
//   *Date / author / rating line*
//   ## Subtitle
//   Body text...            <- put <!--more--> anywhere to choose where the excerpt ends

const fs = require("fs");
const path = require("path");
const { marked } = require("marked");

const SECTIONS = [
    { dir: "blogs", entries: "blog_entries", name: "Blogs" },
    { dir: "books", entries: "book_entries", name: "Books" },
    { dir: "movies", entries: "movie_entries", name: "Movies" },
];
const EXCERPT_LENGTH = 280;
const RESERVED = ["index", "entry", "devlog"]; // existing pages an entry must not overwrite

marked.setOptions({ breaks: true }); // a single newline starts a new line

// Split a Markdown entry into its parts
function parseEntry(markdown) {
    const lines = markdown.replace(/\r\n?/g, "\n").split("\n");
    const take = (re) => {
        while (lines.length && lines[0].trim() === "") lines.shift();
        const m = lines.length && lines[0].match(re);
        if (m) lines.shift();
        return m ? m[1].trim() : "";
    };
    const title = take(/^#\s+(.*)/);
    const meta = take(/^\*([^*].*)\*\s*$/);
    const subtitle = take(/^##\s+(.*)/);
    const body = lines.join("\n").trim();
    return { title, meta, subtitle, body };
}

function makeExcerpt(body) {
    const moreAt = body.indexOf("<!--more-->");
    let text = moreAt !== -1 ? body.slice(0, moreAt) : body;
    // Strip Markdown syntax down to plain text
    text = text
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace(/<[^>]+>/g, "")
        .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
        .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
        .replace(/[#*_>`]/g, "")
        .replace(/\s+/g, " ")
        .trim();
    if (moreAt === -1 && text.length > EXCERPT_LENGTH) {
        text = text.slice(0, EXCERPT_LENGTH).replace(/\s+\S*$/, "") + "…";
    }
    return text;
}

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function renderPage(section, slug, entry) {
    const title = entry.title || slug;
    return `<!DOCTYPE html>
<!-- Generated by build.js from ${section.entries}/${slug}.md. Edit the .md file, not this one. -->
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${escapeHtml(title)} | Sankalpa Raymondal's ${section.name}</title>
    <link rel="stylesheet" href="../style.css">
</head>
<body>
    <header>
        <nav>
            <a href="index.html">Back to ${section.name}</a>
        </nav>
    </header>

    <main>
        <article class="entry-post">
            <h1 class="entry-title">${escapeHtml(title)}</h1>
${entry.meta ? `            <p class="entry-meta">${escapeHtml(entry.meta)}</p>\n` : ""}${entry.subtitle ? `            <h2 class="entry-subtitle">${escapeHtml(entry.subtitle)}</h2>\n` : ""}            <div class="entry-body">
${marked.parse(entry.body.replace("<!--more-->", ""))}
            </div>
        </article>
    </main>
</body>
</html>
`;
}

function buildSection(section) {
    const entriesDir = path.join(__dirname, section.dir, section.entries);
    const listFile = path.join(__dirname, section.dir, "entries.json");

    // Pages from the previous build, so removed .md files lose their .html too
    let previous = [];
    try { previous = JSON.parse(fs.readFileSync(listFile, "utf8")).map((e) => e.page); } catch (e) {}

    const files = fs.existsSync(entriesDir)
        ? fs.readdirSync(entriesDir).filter((f) => f.endsWith(".md") && !f.startsWith("_"))
        : [];
    const list = [];
    for (const file of files.sort().reverse()) { // newest first
        const slug = file.replace(/\.md$/, "");
        if (RESERVED.includes(slug.toLowerCase()) || !/^[\w-]+$/.test(slug)) {
            console.warn(`  skipped ${section.entries}/${file}: use only letters, numbers, - and _ (and not ${RESERVED.join("/")})`);
            continue;
        }
        const entry = parseEntry(fs.readFileSync(path.join(entriesDir, file), "utf8"));
        const page = `${slug}.html`;
        fs.writeFileSync(path.join(__dirname, section.dir, page), renderPage(section, slug, entry));
        list.push({ page, title: entry.title || slug, meta: entry.meta, subtitle: entry.subtitle, excerpt: makeExcerpt(entry.body) });
    }

    for (const page of previous) {
        if (!list.some((e) => e.page === page)) fs.rmSync(path.join(__dirname, section.dir, page), { force: true });
    }
    fs.writeFileSync(listFile, JSON.stringify(list, null, 2) + "\n");
    console.log(`${section.name}: ${list.length} entr${list.length === 1 ? "y" : "ies"}`);
}

function buildAll() {
    SECTIONS.forEach(buildSection);
}

buildAll();

if (process.argv.includes("--watch")) {
    let timer;
    for (const section of SECTIONS) {
        const dir = path.join(__dirname, section.dir, section.entries);
        if (!fs.existsSync(dir)) continue;
        fs.watch(dir, () => {
            clearTimeout(timer);
            timer = setTimeout(() => {
                try { buildAll(); } catch (e) { console.error(e); }
            }, 200);
        });
    }
    console.log("Watching for changes… (Ctrl+C to stop)");
}
